export function getCurrentIranMonth() {
  try {
    const formatter = new Intl.DateTimeFormat("en-US-u-ca-persian", {
      timeZone: "Asia/Tehran",
      month: "numeric",
    });
    return parseInt(formatter.format(new Date()), 10);
  } catch {
    const now = new Date();
    const gy = now.getFullYear();
    const gm = now.getMonth() + 1;
    const gd = now.getDate();
    const gdm = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
    const gyRem = gy - (gy <= 1600 ? 621 : 1600);
    const gy2 = gm > 2 ? gyRem + 1 : gyRem;
    let days =
      365 * gyRem +
      Math.floor((gy2 + 3) / 4) -
      Math.floor((gy2 + 99) / 100) +
      Math.floor((gy2 + 399) / 400) -
      80 +
      gd +
      gdm[gm - 1];
    days %= 12053;
    days %= 1461;
    if (days > 365) {
      days = (days - 1) % 365;
    }
    return days < 186 ? 1 + Math.floor(days / 31) : 7 + Math.floor((days - 186) / 30);
  }
}

export function getCurrentIranSeason() {
  const month = getCurrentIranMonth();
  if (month >= 1 && month <= 3) return "spring";
  if (month >= 4 && month <= 6) return "summer";
  if (month >= 7 && month <= 9) return "autumn";
  return "winter";
}

